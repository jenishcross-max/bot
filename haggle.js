/* ---------------- режим «Торгаш» ----------------
   Клиенты торгуются всегда — на базаре это часть покупки, а не наглость. Бот
   отбивается артистично и с шутками, но цену не двигает: скидку имеет право дать
   только владелец, а не языковая модель.

   Отсюда два слоя защиты. Первый — жёсткие правила в промпте. Второй — фильтр
   ответа: если модель всё-таки пообещала скидку, ответ подменяется заготовкой.
   Заготовки же выручают, когда Groq недоступен: клиент получит шутку, а не тишину.

   Про регулярки ниже: \b и \w в JS работают только с латиницей, поэтому «конец
   слова» пишем через (?![а-яё]), а «хвост слова» — через [а-яё]*. Иначе «дорого»
   ловится внутри «дорогой», а «сделаю скидку» не ловится вообще.
------------------------------------------------------------------------- */

const { notifyAdmins } = require('./notify');

const HAGGLE_MODE = process.env.HAGGLE_MODE === 'true';
// Игровая строчка с раундом и титулом. Для серьёзного магазина отключается.
const BADGES = process.env.HAGGLE_BADGES !== 'false';
// Раунд, после которого владельцу уходит уведомление: клиент, который торгуется
// четвёртый раз, уже хочет купить — это горячая заявка, а не праздный вопрос.
// 0 — уведомления выключены.
const NOTIFY_ROUND = Number(process.env.HAGGLE_NOTIFY_ROUND || 4);
// Единственная уступка, которую боту разрешено обещать. Всё, что стоит магазину
// денег (доставка, подарки, рассрочка), сюда попадать не должно: такие обещания
// раздаёт владелец, а не бот.
const BONUS = process.env.HAGGLE_BONUS || 'придержу товар до конца дня';

// Попытки торга по чатам: chatId -> { n, at, notified }
const attempts = new Map();
// Через полдня молчания счётчик обнуляется: иначе клиент вернётся через неделю
// сразу «легендой базара» и шутки пойдут не с той ноты.
const RESET_AFTER_MS = 6 * 60 * 60 * 1000;

const HAGGLE_INTENT = new RegExp(
  [
    'скидк', 'скидочк', 'подешевле', 'дешевле', 'уступ', 'сбав', 'сбрось',
    'скин(ь|ем|у|ете|ешь|уть|те)', 'торг(?![а-яё])', 'торгу', 'поторгу', 'торговать',
    'дорого(?![а-яё])', 'дороговат', 'дорогонько', 'кусается', 'не по карману',
    'последняя цена', 'окончательная цена', 'крайняя цена', 'самая низкая',
    // «отдадите?» в переписке с магазином — всегда про цену, поэтому без «за»
    'отдад(и|ё|е)те', 'отдашь', 'продад(и|ё|е)те за', 'уступите',
    'торг уместен', 'без торга', 'сколько скинете',
    // «а если 90 000?», «дам 85к», «а если за 90 000» — своя цена это тоже торг
    '(а если|дам|даю|возьму за|беру за|готов за)\\s+\\d',
    'если\\s+за\\s+\\d',
  ].join('|'),
  'i'
);

/* --- своя цена клиента ---
   «а за 90 000 отдадите?», «85к и беру». Шутка про конкретную сумму смешнее
   общей, поэтому число достаём отдельно. Разряды жадно и целиком: при ленивом
   квантификаторе «90 000» читается как «90» и предложение теряется. */
const OFFER_RE =
  /(?:за|по|дам|даю|если|беру|возьму)\s+(\d[\d\s .,]*\d|\d)\s*(к(?![а-яё])|k|тыс[а-яё]*)?/gi;

function namedOffer(text) {
  let found = null;
  for (const m of String(text).matchAll(OFFER_RE)) {
    const num = Number(m[1].replace(/\D/g, ''));
    if (!Number.isFinite(num) || num <= 0) continue;
    const value = m[2] ? num * 1000 : num;
    // Мелкие числа — это размеры, количество и «айфон 17», а не предложение цены.
    if (value < 100) continue;
    found = value;
  }
  return found;
}

// Разряды пробелами: 90000 -> «90 000». Пробел неразрывный, чтобы WhatsApp не
// переносил сумму на две строки.
function money(n) {
  return String(n).replace(/\B(?=(\d{3})+(?!\d))/g, ' ');
}

// Титулы без эмодзи: подставленный в промпт значок модель всё равно теряет и
// пишет «Мастер торга !». Значок добавляем сами — в плашке и в заготовках.
const TITLES = [
  'Новичок базара',
  'Уверенный покупатель',
  'Опытный торгаш',
  'Мастер торга',
  'Легенда базара',
];
const ICONS = ['', '', '', ' 🏆', ' 👑'];

function title(n) {
  return TITLES[Math.min(n, TITLES.length) - 1];
}

function icon(n) {
  return ICONS[Math.min(n, ICONS.length) - 1];
}

/* --- заготовки ---
   Играют роль запасного аэродрома: при ошибке Groq и при срабатывании фильтра
   скидок. По раундам — чтобы упорному клиенту не приходила одна и та же шутка. */
const LINES = {
  1: [
    'Скидка? Я по этой цене сам себе не продаю 😄 Зато цена честная.',
    'Ох, начинается 🙂 От того, что вы улыбаетесь, ценник, к сожалению, не тает.',
    'Торгуетесь красиво! Но ценник у меня приклеен намертво.',
  ],
  2: [
    'Вы почти уговорили. Почти — это когда цена осталась прежней 😅',
    'Скинул бы, но тогда придётся продать стул, на котором сижу.',
    'Спросил у калькулятора — он посмеялся и показал ту же цифру.',
  ],
  3: [
    'Клянусь базаром: дешевле бывает только у тех, кто потом трубку не берёт 😌',
    'Мой директор — я. И себе скидку я принципиально не подписываю.',
    'Цена не двигается. Двигается только очередь за этим товаром.',
  ],
  4: [
    `Всё, сдаюсь: вы официально ${title(4)} 🏆 Цена прежняя, но ${BONUS}.`,
    `Такому напору положен титул: ${title(4)} 🏆 Скидки не будет, а вот ${BONUS}.`,
  ],
  5: [
    `Вы упорнее моего поставщика, а это диагноз 😄 ${title(5)} — ваш титул, цена — моя.`,
    `Уважаю. Цена не изменилась, уважение — бесплатно 🤝 И ${BONUS}.`,
  ],
};

// Отдельные шутки, когда клиент назвал свою сумму: они смешнее общих.
const OFFER_LINES = [
  (s) => `За ${s}? За ${s} я вам могу продать фотографию этого товара 📷 А сам товар — по ценнику.`,
  (s) => `${s}… Записал. Показал бухгалтеру. Бухгалтер плачет. Цена прежняя 😅`,
  (s) => `Красивое число ${s}. Но моё красивее — оно на ценнике.`,
];

function pick(list, seed) {
  return list[seed % list.length];
}

function fallback(ctx) {
  const tier = LINES[Math.min(ctx.state.n, 5)] || LINES[5];
  if (ctx.offer && ctx.state.n < 4) {
    return pick(OFFER_LINES, ctx.state.n)(money(ctx.offer));
  }
  return pick(tier, ctx.state.n);
}

/* --- фильтр скидок ---
   Ловим только реальные обещания. Отказы («скидок нет», «скидку сделать не могу»)
   пропускаем: текст перед совпадением проверяем на отрицание. */
const GRANT_PATTERNS = [
  /скидк[а-яё]*\s+(в\s+)?\d+\s*%/i,
  /\d+\s*%\s*(скидк|дешевле)/i,
  /[-–—]\s?\d{1,2}\s?%/,
  /минус\s*\d/i,
  /(отда|уступ|скин|отпущ|продам)[а-яё]*\s+(вам\s+|тебе\s+)?за\s+\d/i,
  /(специальн|особ|персональн)[а-яё]*\s+цен[а-яё]*/i,
  /(сдела|дела|дам|даю|готов)[а-яё]*\s+(вам\s+)?скидк/i,
  /только\s+для\s+вас\s+\d/i,
  /(могу|можем)\s+уступ/i,
];
// Отрицание ищем целым словом: без (?![а-яё]) «бы» нашлось бы внутри «обычная»,
// и настоящая скидка проскочила бы как «отменённая».
const NEGATION =
  /(^|[^а-яё])(не|нет|нельзя|невозможн[а-яё]*|без|никак[а-яё]*|увы|исключен[а-яё]*)(?![а-яё])[^.!?]{0,40}$/i;

function grantsDiscount(text) {
  const s = String(text);
  return GRANT_PATTERNS.some((re) => {
    const m = re.exec(s);
    if (!m) return false;
    return !NEGATION.test(s.slice(Math.max(0, m.index - 40), m.index));
  });
}

function bump(chatId) {
  const now = Date.now();
  const prev = attempts.get(chatId);
  const state = prev && now - prev.at < RESET_AFTER_MS ? prev : { n: 0, notified: false };
  state.n += 1;
  state.at = now;
  attempts.set(chatId, state);
  return state;
}

function personaPrompt(ctx) {
  const lines = [
    `Клиент торгуется, это попытка №${ctx.state.n}. Отвечай как весёлый базарный продавец,`,
    'который обожает торг. На этот ответ указание «кратко и по делу» из инструкции',
    'выше не распространяется: шутка важнее делового тона. Но правила железные:',
    '1. ЦЕНУ НЕ СНИЖАЙ. Ни на сом, ни на процент, ни «в виде исключения».',
    '2. Не называй новую цену, размер скидки, «специальную цену», «только для вас» и рассрочку.',
    '3. Не обещай ничего, что стоит магазину денег: ни бесплатной доставки, ни подарков.',
    `4. Разрешено только это: ${BONUS}; предложить более дешёвый аналог из каталога;`,
    '   передать заявку менеджеру, если клиент готов купить.',
    '5. Максимум три коротких предложения и один эмодзи, без грубости и без «уважаемый клиент».',
    '6. Цену из каталога назови ровно один раз — в конце, как окончательную. Не повторяй её дважды.',
    '',
    // Без примеров модель соблюдает правила, но отвечает канцелярски: «цену снизить
    // не могу». Пара образцов тона решает это лучше любых прилагательных в промпте.
    'Примеры нужного тона — не копируй дословно, придумывай своё в том же духе:',
    ...LINES[Math.min(ctx.state.n, 3)].map((s) => `— ${s}`),
  ];
  if (ctx.offer) {
    lines.push(
      `Клиент предлагает свою цену — ${money(ctx.offer)}. Обыграй эту сумму шуткой и не соглашайся.`
    );
  }
  if (ctx.state.n >= 4) {
    lines.push(
      `Клиент упорный: признай это с уважением, присвой ему шуточный титул «${title(ctx.state.n)}» ` +
        `и пообещай, что ${BONUS}. Цена всё равно прежняя.`
    );
  }
  return lines.join('\n');
}

function maybeNotify(chatId, ctx, userMessage) {
  if (!NOTIFY_ROUND || ctx.state.n < NOTIFY_ROUND || ctx.state.notified) return;
  // Один раз за серию торга, иначе владелец получит десять одинаковых сообщений.
  ctx.state.notified = true;

  const digits = String(chatId || '').split('@')[0].replace(/\D/g, '');
  notifyAdmins(
    `💰 Клиент активно торгуется (${ctx.state.n}-я попытка)\n\n` +
      `Номер: ${digits ? `+${digits}` : chatId}\n` +
      `Сообщение: «${userMessage}»\n` +
      (ctx.offer ? `Своя цена клиента: ${money(ctx.offer)}\n` : '') +
      `\nБот держит цену. Если готовы подвинуться — самое время написать самому.`
  ).catch((err) => console.error('Не удалось уведомить о торге:', err));
}

/* --- публичный интерфейс --- */

// Вызывается на каждое сообщение. Возвращает контекст торга или null.
function detect(chatId, userMessage) {
  if (!HAGGLE_MODE || !HAGGLE_INTENT.test(userMessage)) return null;

  const state = bump(chatId);
  const ctx = { state, offer: namedOffer(userMessage) };
  ctx.prompt = personaPrompt(ctx);
  maybeNotify(chatId, ctx, userMessage);
  return ctx;
}

// Последний рубеж: что бы модель ни придумала, скидка до клиента не доедет.
function guard(reply, ctx) {
  if (!grantsDiscount(reply)) return reply;
  console.warn('[торгаш] модель пообещала скидку — ответ заменён заготовкой');
  return fallback(ctx);
}

function badge(ctx) {
  if (!BADGES) return '';
  return `\n\n🎮 Раунд ${ctx.state.n} · ${title(ctx.state.n)}${icon(ctx.state.n)}`;
}

function reset(chatId) {
  attempts.delete(chatId);
}

module.exports = {
  HAGGLE_MODE,
  detect,
  guard,
  badge,
  fallback,
  reset,
  // экспортируется для демо-скрипта и отладки
  _internal: { grantsDiscount, namedOffer, HAGGLE_INTENT },
};
