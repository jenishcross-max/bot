-- Этап I. Выполните это один раз в Supabase: SQL Editor → New query → Run.
-- Скрипт ничего не удаляет: он только снимает защиту, из-за которой записи
-- не сохранялись, и добавляет услугам длительность.

-- 1. Записи клиентов.
--    Пока row level security включена, а политик нет, база молча отклоняет
--    вставку: бот отвечает клиенту «записала», а в таблице пусто. Ключ у нас
--    служебный и лежит только на сервере, так что защищать нечего.
alter table appointments disable row level security;

-- 2. Длительность услуги в минутах.
--    Раньше всё считалось одним числом SALON_SLOT_MINUTES: и шаг сетки, и
--    длина записи. Стрижка на 40 минут съедала час, а окраска на три часа
--    занимала один — и бот предлагал клиенту время, когда мастер ещё занят.
--    Пусто = берём длительность по умолчанию (60 минут).
alter table products add column if not exists duration_minutes integer;

-- 3. Длительность самой записи.
--    Хранится отдельно от услуги нарочно: цену и длительность услуги владелец
--    правит когда захочет, а уже созданная запись должна занимать столько,
--    сколько занимала в момент записи, — иначе вчерашнее расписание поедет само.
alter table appointments add column if not exists duration_minutes integer;

-- Проверка: должно вернуть две строки.
select table_name, column_name
from information_schema.columns
where column_name = 'duration_minutes' and table_name in ('products', 'appointments');
